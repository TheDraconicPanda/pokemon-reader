"""Generate holdable-item membership from the pinned Platinum native item data.
Usage: python3 scripts/build-trade-items.py work/pokeplatinum
"""
import json
import sys
from pathlib import Path
source = Path(sys.argv[1])
items = (source / 'generated/items.txt').read_text().splitlines()
allowed = []
for ident, symbol in enumerate(items):
    if not ident or ident > 467 or not symbol.startswith('ITEM_'):
        continue
    file = source / 'res/items/data' / (symbol[5:].lower() + '.json')
    if file.exists():
        data = json.loads(file.read_text())
        if not data['preventToss'] and not symbol.startswith('ITEM_UNUSED'):
            allowed.append(ident)
Path('js/data/gen4-trade-items.js').write_text('// Generated by scripts/build-trade-items.py from native preventToss item attributes.\nexport const GEN4_TRADE_ITEMS = new Set(' + json.dumps(allowed,separators=(',',':')) + ');\n')
