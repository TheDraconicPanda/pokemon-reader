"""Offline Platinum Reader tables. Usage: python scripts/build-platinum-reader.py CHECKOUT

The checkout must be the pinned pret/pokeplatinum revision below. Identifiers
are index-based game constants; labels/types/stats never use modern API data.
"""
import hashlib, json, pathlib, re, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SOURCE = pathlib.Path(sys.argv[1])
REVISION = '49f78f35ccd8c6880e189d23a630eef2976c44ac'
assert subprocess.check_output(['git', '-C', str(SOURCE), 'rev-parse', 'HEAD'], text=True).strip() == REVISION
assert not subprocess.check_output(['git', '-C', str(SOURCE), 'status', '--porcelain', '--untracked-files=no'], text=True).strip()
used = {}

def read(name):
    raw = (SOURCE / name).read_bytes()
    used[name] = {'url': f'https://github.com/pret/pokeplatinum/blob/{REVISION}/{name}', 'sha256': hashlib.sha256(raw).hexdigest()}
    return raw.decode()

def document(name): return json.loads(read(name))
def identifiers(name): return {name: i for i, name in enumerate(read(f'generated/{name}.txt').splitlines())}
species_ids, move_ids, ability_ids, item_ids = (identifiers(n) for n in ['species', 'moves', 'abilities', 'items'])
regional = [species_ids[n] for n in document('res/pokemon/sinnoh_pokedex.json')[1:]]
assert len(regional) == len(set(regional)) == 210 and regional[:3] == [387, 388, 389] and regional[-1] == 487
growth_names = {'MEDIUM_FAST':'medium-fast', 'ERRATIC':'erratic', 'FLUCTUATING':'fluctuating', 'MEDIUM_SLOW':'medium-slow', 'FAST':'fast', 'SLOW':'slow'}
gender_ratios = {key:int(value) for key,value in re.findall(r'^(GENDER_RATIO_\w+) = (\d+)$', read('generated/gender_ratios.txt'), re.M)}
records = {}
evolutions = []
for name, ident in species_ids.items():
    if not 1 <= ident <= 493: continue
    slug = name.removeprefix('SPECIES_').lower()
    p = document(f'res/pokemon/{slug}/data.json')
    for edge in p.get('evolutions', []):
        param = edge[1] if len(edge) > 2 else 0
        if isinstance(param, str):
            param = next((ids[param] for ids in [item_ids, move_ids, species_ids] if param in ids), param)
        evolutions.append({'from': ident, 'to': species_ids[edge[-1]], 'method': edge[0], 'param': param})
    records[ident] = {'types': list(dict.fromkeys(t.removeprefix('TYPE_').lower() for t in p['types'])),
        'stats': [p['base_stats'][s] for s in ['hp','attack','defense','special_attack','special_defense','speed']],
        'abilities': list(dict.fromkeys(ability_ids[a] for a in p['abilities'] if a != 'ABILITY_NONE')),
        'growthRate': growth_names[p['exp_rate'].removeprefix('EXP_RATE_')], 'genderRatio':gender_ratios[p['gender_ratio']]}
abilities = {i: m['en_US'] for i, m in enumerate(document('res/text/ability_names.json')['messages']) if 1 <= i <= 123}
moves = {}
for symbol, ident in move_ids.items():
    if not 1 <= ident <= 467: continue
    move = document('res/moves/' + symbol.removeprefix('MOVE_').lower() + '/data.json')
    moves[ident] = {'name': move['name'], 'basePP': move['pp']}
items = {}
for file in sorted((SOURCE / 'res/items/data').glob('*.json')):
    item = document(file.relative_to(SOURCE).as_posix())
    # The ordered generated list supplies cartridge item IDs.
    items[file.stem] = item.get('name')
items = {ident: items.get(symbol.removeprefix('ITEM_').lower()) for symbol, ident in item_ids.items() if ident <= 467}
characters = {}
for line in read('tools/msgenc/charmap.txt').splitlines():
    match = re.fullmatch(r'([0-9A-Fa-f]{4})=(.)', line)
    if match: characters[int(match[1],16)] = match[2]
# The source charmap uses a visual full-width hyphen alias for the Japanese
# prolonged sound mark. PKHeX's canonical Unicode for this same code is U+30FC.
assert characters[0xF1] == '－'
characters[0xF1] = 'ー'
characters[0xEE], characters[0xEF] = '♂', '♀'
# The decomp charmap omits the reserved Korean 0x400 entry, shifting only
# 0x401..0x40F. Later rows are correctly indexed. Confirmed by PKHeX's
# StringConverter4Util.TableKOR and all 493 independently encoded Korean names.
for code in range(0x40F, 0x400, -1): characters[code] = characters[code - 1]
del characters[0x400]
read('include/constants/versions.h')
read('include/trainer_info.h')
read('include/savedata.h')
read('src/savedata.c')
read('src/pokemon.c')
read('src/evolution.c')
read('src/pc_boxes.c')
data = {'schemaVersion':1, 'gameId':'platinum', 'revision':REVISION, 'regional':regional,
        'species':records, 'evolutions':evolutions, 'abilities':abilities, 'moves':moves, 'items':items, 'characters':characters}
out = ROOT / 'js/data/games/platinum'; out.mkdir(parents=True, exist_ok=True)
(out / 'reader-reference.js').write_text('// Generated by scripts/build-platinum-reader.py; primary Generation IV facts.\nexport const PLATINUM_READER = ' + json.dumps(data, ensure_ascii=False, separators=(',',':')) + ';\n')
(ROOT / 'docs/platinum-reader-sources.json').write_text(json.dumps({'revision':REVISION,'sources':used,'characterNormalization':{'reference':'https://github.com/kwsch/PKHeX/blob/a9ff30657073b26825929a65ef58e61f99a1fe6f/PKHeX.Core/PKM/Strings/StringConverter4Util.cs','codes':['00EE','00EF','00F1','0400-040F'],'reason':'Normalize gender/prolonged-sound glyph aliases and correct the missing reserved Korean entry; independently checked across 3451 native names.'}}, indent=2) + '\n')
print(f'Platinum: {len(regional)} regional, {len(records)} species, {len(moves)} moves, {len(characters)} characters')
